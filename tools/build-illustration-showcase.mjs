import { spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const entries = readJson(join(root, 'showcase/scenes.json'));
const check = process.argv.includes('--check');
const workspace = mkdtempSync(join(tmpdir(), 'ai-graph-showcase-'));
const files = new Map();
const downloads = new Map();

function readJson(file) {
  return JSON.parse(readFileSync(file, 'utf8'));
}

function readShowcase(file) {
  return readFileSync(join(root, 'showcase', file), 'utf8');
}

function svgDataUrl(path) {
  return 'data:image/svg+xml;base64,' + files.get(path).toString('base64');
}

function escapeHtml(text) {
  return text.replaceAll('&', '&amp;').replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;').replaceAll('"', '&quot;');
}

function renderGallery(catalog) {
  return catalog.map(({ id, industry, placement, label, palettes }) => {
    const source = svgDataUrl(palettes[0].svg);
    return `          <a class="gallery-item" data-gallery-scene="${escapeHtml(id)}" href="${source}" download="${escapeHtml(id)}.svg">
            <img class="gallery-image" src="${source}" width="960" height="600" alt="">
            <div class="gallery-label">
              <span class="gallery-text"><span class="gallery-meta">${escapeHtml(industry)} / ${escapeHtml(placement)}</span><strong>${escapeHtml(label)}</strong></span>
              <span class="gallery-arrow" aria-hidden="true">↓</span>
            </div>
          </a>`;
  }).join('\n');
}

function safeScriptJson(value) {
  return JSON.stringify(value).replaceAll('<', '\\u003c');
}

function buildPage(catalog) {
  const javascript = [
    "'use strict';",
    `window.showcaseCatalog = ${safeScriptJson(catalog)};`,
    `window.showcaseDownloads = ${safeScriptJson(Object.fromEntries(downloads))};`,
    readShowcase('app.js'),
  ].join('\n');
  const content = {
    STYLES: readShowcase('styles.css'),
    HERO: svgDataUrl(catalog[0].palettes[0].svg),
    GALLERY: renderGallery(catalog),
    SCRIPT: javascript,
  };
  const template = readShowcase('index.template.html');
  const page = template.replace(/<!-- SHOWCASE_(STYLES|HERO|GALLERY|SCRIPT) -->/g, (_, name) => content[name]);
  return '<!-- Generated by npm run showcase:build from index.template.html. -->\n' + page;
}

function buildScene(id, brief, scene) {
  const compiled = join(workspace, id + '.scene.json');
  const svg = join(workspace, id + '.svg');
  const result = spawnSync(process.execPath, [
    join(root, 'tools/pipeline.mjs'),
    '--brief', brief, '--scene', scene, '--outScene', compiled, '--outSvg', svg,
  ], { cwd: root, encoding: 'utf8' });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(id + '\n' + result.stdout + result.stderr);
  const source = readFileSync(svg);
  if (source.includes('{{slot:')) throw new Error('Unresolved slot in ' + id);
  const destination = 'illustrations/' + id + '.svg';
  files.set(destination, source);
  downloads.set(destination, source.toString('utf8'));
  console.log('通过 ' + id + ' · 结构检查、视觉检查、SVG');
  return destination;
}

try {
  const catalog = entries.map(({ id, industry, placement, label, brief, scene, defaultName, alternate }) => {
    downloads.set('../' + brief, readFileSync(join(root, brief), 'utf8'));
    downloads.set('../' + scene, readFileSync(join(root, scene), 'utf8'));
    const base = readJson(join(root, brief));
    const { description, accent, background, highlight } = base.layout.slots;
    const defaultSvg = buildScene(id, brief, scene);
    const alternateId = id + '-alternate';
    const alternateBrief = 'illustrations/' + alternateId + '.brief.json';
    const alternateInput = join(workspace, alternateId + '.brief.json');
    Object.assign(base.layout.slots, alternate.slots);
    base.constraints.brandColor = alternate.slots.accent;
    const briefBytes = Buffer.from(JSON.stringify(base, null, 2) + '\n');
    writeFileSync(alternateInput, briefBytes);
    files.set(alternateBrief, briefBytes);
    downloads.set(alternateBrief, briefBytes.toString('utf8'));
    const alternateSvg = buildScene(alternateId, alternateInput, scene);
    return {
      id, industry, placement, label, description, scene: '../' + scene,
      palettes: [
        { name: defaultName, accent, background, highlight, brief: '../' + brief, svg: defaultSvg },
        { name: alternate.name, description: alternate.slots.description, accent: alternate.slots.accent, background: alternate.slots.background, highlight: alternate.slots.highlight, brief: alternateBrief, svg: alternateSvg },
      ],
    };
  });
  files.set('index.html', Buffer.from(buildPage(catalog)));
  for (const [relative, contents] of files) {
    const target = join(root, 'showcase', relative);
    if (check) {
      if (!readFileSync(target).equals(contents)) throw new Error('Run npm run showcase:build to update ' + relative);
    } else {
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, contents);
    }
  }
  console.log(check ? '生成文件逐字节一致。' : '本地入口已就绪 · showcase/index.html');
} finally {
  rmSync(workspace, { recursive: true, force: true });
}
